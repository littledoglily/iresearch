from render import *

def csi_rows_for(F, col_prefix):
    return [r for r in F['csi'].rows if r['desc'].startswith('列 %s ' % col_prefix)]

def rowtable(rows, with_hex=True):
    o = ['| `.csi` 偏移 | 长度 | 字节 | 含义 |', '|---|---|---|---|']
    for r in rows:
        desc = r['desc'].split(': ', 1)[1] if ': ' in r['desc'] else r['desc']
        o.append('| %d | %d | `%s` | %s |' % (r['off'], r['size'], r['hex'], san(desc)))
    return '\n'.join(o)

